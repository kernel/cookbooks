"""Optional demo target for the Kernel File I/O cookbook.

This is a single-file Modal app that serves a tiny "parking receipt lookup"
website matching the selectors `main.py` automates out of the box:

- `input#email` and `input#order_number` on the lookup form
- `button#generateBtn` submits the form
- `a.btn-download` on the confirmation page serves a PDF receipt with a
  `Content-Disposition: attachment` header, which triggers a real browser
  download that the cookbook captures via CDP

Deploy it to your own Modal workspace with one command:

    modal deploy demo_site.py

Then point the cookbook at the printed URL:

    WEBSITE_URL=https://<workspace>--file-io-demo-site-web.modal.run uv run main.py

The app scales to zero when idle, so it costs nothing at rest. It has no
state, no dependencies beyond FastAPI, and generates the PDF in pure Python.
"""

