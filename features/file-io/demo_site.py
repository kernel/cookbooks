def _page(body: str) -> str:
    return f"""<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>Acme Parking Receipts</title>
  <style>{_STYLE}</style>
</head>
<body>
  <div class="card">{body}</div>
</body>
</html>"""


def _pdf_escape(text: str) -> str:
    return text.replace("\\", r"\\").replace("(", r"\(").replace(")", r"\)")


def _build_receipt_pdf(email: str, order_number: str) -> bytes:
    """Build a small one-page PDF receipt in pure Python (no dependencies)."""
    issued = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    lines = [
        ("Acme Parking - Official Receipt", 20),
        ("", 12),
        (f"Order number: {order_number}", 12),
        (f"Email: {email}", 12),
        (f"Issued: {issued}", 12),
        ("", 12),
        ("Location: Lot 42, 100 Demo Way", 12),
        ("Duration: 2 hours 15 minutes", 12),
        ("Amount paid: $12.50", 12),
        ("", 12),
        ("Generated by the Kernel File I/O cookbook demo site.", 10),
    ]

    parts = ["BT", "/F1 12 Tf", "1 0 0 1 72 720 Tm", "16 TL"]
    for text, size in lines:
        parts.append(f"/F1 {size} Tf")
        parts.append(f"({_pdf_escape(text)}) Tj")
        parts.append("T*")
    parts.append("ET")
    content = "\n".join(parts).encode("latin-1", "replace")

    objects = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] "
        b"/Resources << /Font << /F1 5 0 R >> >> /Contents 4 0 R >>",
        b"<< /Length %d >>\nstream\n%s\nendstream" % (len(content), content),
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    ]

    out = bytearray(b"%PDF-1.4\n")
    offsets = []
    for i, obj in enumerate(objects, start=1):
        offsets.append(len(out))
        out += b"%d 0 obj\n%s\nendobj\n" % (i, obj)

    xref_pos = len(out)
    out += b"xref\n0 %d\n" % (len(objects) + 1)
    out += b"0000000000 65535 f \n"
    for offset in offsets:
        out += b"%010d 00000 n \n" % offset
    out += (
        b"trailer\n<< /Size %d /Root 1 0 R >>\nstartxref\n%d\n%%%%EOF\n"
        % (len(objects) + 1, xref_pos)
    )
    return bytes(out)


# min_containers=0 (the default) means the app scales to zero when idle and
# costs nothing at rest. scaledown_window keeps a warm container briefly so
# multi-step automation runs stay snappy.
@app.function(image=image, min_containers=0, scaledown_window=120)
@modal.asgi_app()
def web():
    from fastapi import FastAPI
    from fastapi.responses import HTMLResponse, Response

    api = FastAPI(title="Kernel File I/O demo site")

    @api.get("/", response_class=HTMLResponse)
    def lookup_form() -> str:
        return _page(
            """
            <span class="badge">Demo target</span>
            <h1>Parking receipt lookup</h1>
            <p class="sub">Enter the email and order number from your booking
            to retrieve your receipt.</p>
            <form action="/receipt" method="get">
              <label for="email">Email address</label>
              <input id="email" name="email" type="email" required
                     placeholder="you@example.com">
              <label for="order_number">Parking reference</label>
              <input id="order_number" name="order_number" type="text" required
                     placeholder="110011001">
              <button id="generateBtn" type="submit">Look Up Parking</button>
            </form>
            """
        )

    @api.get("/receipt", response_class=HTMLResponse)
    def receipt_page(email: str = "", order_number: str = "") -> str:
        from html import escape
        from urllib.parse import urlencode

        query = urlencode({"email": email, "order_number": order_number})
        return _page(
            f"""
            <span class="badge">Order found</span>
            <h1>Receipt ready</h1>
            <p class="sub">We found a parking session matching your details.
            Download the PDF receipt below.</p>
            <dl>
              <div><dt>Order number</dt><dd>{escape(order_number)}</dd></div>
              <div><dt>Email</dt><dd>{escape(email)}</dd></div>
              <div><dt>Amount paid</dt><dd>$12.50</dd></div>
            </dl>
            <a class="btn-download" href="/receipt.pdf?{query}">
              Download receipt (PDF)
            </a>
            """
        )

    @api.get("/receipt.pdf")
    def receipt_pdf(email: str = "", order_number: str = "") -> Response:
        safe_order = "".join(
            ch for ch in order_number if ch.isalnum() or ch in "-_"
        ) or "receipt"
        pdf = _build_receipt_pdf(email, order_number)
        return Response(
            content=pdf,
            media_type="application/pdf",
            headers={
                # The attachment disposition is what makes the browser treat
                # this as a download, which the cookbook captures via CDP.
                "Content-Disposition": (
                    f'attachment; filename="parking-receipt-{safe_order}.pdf"'
                )
            },
        )

    return api
